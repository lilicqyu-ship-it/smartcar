extern IfxCpu_syncEvent cpuSyncEvent;

void core2_main(void)
{
#ifdef USE_SPI_LINK
    uint32 nextTelMs;
    uint32 nextDiagMs;
    uint32 nextSpdMs;
#endif

    IfxCpu_enableInterrupts();

    /* CPU2 watchdog intentionally stays DISABLED (doc 21 SS18 C8): a hung
     * link pump cannot move the motors (CPU1's 150 ms command-loss ramp-stop
     * and CPU0's 100 ms heartbeat stop them first), and per doc 21 SS7.2 a
     * CPU2 fault must reset only CPU2 - that needs the production SMU alarm
     * routing. The CPU2 WDT alarm here would reset the whole vehicle.
     * Revisit together with the SS7.2 watchdog chain. */
    IfxScuWdt_disableCpuWatchdog(IfxScuWdt_getCpuWatchdogPassword());

    /* Wait for CPU sync event */
    IfxCpu_emitEvent(&cpuSyncEvent);
    IfxCpu_waitEvent(&cpuSyncEvent, 1);

    STIME_init();

#ifdef USE_SPI_LINK

    /* First rung of the clock ladder: gate G1 is a waveform compatibility test,
     * so it starts at 1 MHz and only climbs on measured error rates (22 SS8). */
    LINK_init(SPIHAL_CLK_1M);
    OTAAPP_init();                       /* OTA receiver (doc 24 SS5.3)      */
    nextTelMs  = STIME_nowMs() + LINK_TELEMETRY_PERIOD_MS;
    nextDiagMs = STIME_nowMs() + LINK_DIAG_PERIOD_MS;
    nextSpdMs  = STIME_nowMs() + LINK_SPEED_PERIOD_MS;

    while (1)
    {
        LINK_main();                       /* pump: registers, read, write      */
        OTAAPP_tick();                     /* self-test confirm (doc 24 SS5.2)  */

        if ((sint32)(STIME_nowMs() - nextTelMs) >= 0)
        {
            nextTelMs += LINK_TELEMETRY_PERIOD_MS;
            link_sendTelemetry();          /* keeps WRDMA traffic flowing for G5 */
            link_sendPendingEvents();      /* DPT event frames queued by CPU0    */
        }

        if ((sint32)(STIME_nowMs() - nextDiagMs) >= 0)
        {
            nextDiagMs += LINK_DIAG_PERIOD_MS;
            LINK_diagPrint();              /* bench: dump SPI link state to UART  */
        }

        if ((sint32)(STIME_nowMs() - nextSpdMs) >= 0)
        {
            nextSpdMs += LINK_SPEED_PERIOD_MS;
            link_speedPrint();             /* bench: wheel speeds + odometer     */
        }
    }

#else

    /* Initialize the binary protocol parser (byte stream comes from WiFi) */
    PROTO_init();

    /* Initialize the ESP32-C6 AT module on ASCLIN1 (P15.0 TX / P15.1 RX) */
    WIFI_init();

    WIFI_main();                           /* never returns */

    while (1)
    {
    }

#endif
}
