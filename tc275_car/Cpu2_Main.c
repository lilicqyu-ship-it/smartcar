/* 22 SS6: telemetry is aggregated at 20 ms. */
#define LINK_TELEMETRY_PERIOD_MS  20u

/* Bench diagnostic line rate. Slow on purpose: it is for a human watching the
 * serial console, not for the control path, and one line per 500 ms keeps the
 * shared log ring and ASCLIN0 well clear of the 20 ms telemetry traffic. */
#define LINK_DIAG_PERIOD_MS       500u

/* SDD SS10: fwVer is 0x00MMmmpp. Derived from mw/app_version.h so the
 * telemetry slot always matches the firmware version string (the buildhash
 * half of the §10 version string has no slot in a u32 and is not carried). */
#include "mw/app_version.h"
#define LINK_FW_VERSION           ((((uint32)APP_VERSION_MAJOR) << 16) |                                    (((uint32)APP_VERSION_MINOR) << 8) |                                    ((uint32)APP_VERSION_PATCH))

/* Telemetry fields with a measured source in this build are filled, the rest are
 * zero. The zeros are not placeholders: each one names what has to exist first.
 * Filling a field with a number from another unit would be worse than a zero,
 * because the C6 forwards these bytes to the phone, which prints mm/s, mV and mm.
 *   vMeasL/R     - mm/s, straight from CPU1's encoder task through the xcore
 *                  encoder block (doc 21 SS6.3: the SS5.1 encoder channel this
 *                  field was waiting for). A dead or stopped encoder reads 0,
 *                  which is honest in both cases - the payload has no alive bit.
 *   odoSessionMm - overflow-free average of the two side odometries; both are
 *                  absolute accumulators, so the average is the distance the
 *                  chassis covered, straight or curved.
 *   vTargetL/R   - the CPU0 command (percent*10) converted to mm/s through
 *                  the calibration record's fullScaleMmS (doc 34 SS8.2), the
 *                  same number CPU1 divides the measured speed by, so both
 *                  columns share one calibration and follow a REC_SET at once
 *                  (SDD SS5.2 servo landed 2026-09-27; before that the
 *                  target was a raw percent and stayed 0 here).
 *   batteryMv/Pct- VIN from CPU1's VADC (D24A J6-1 divider on AN4/X2-23,
 *                  EMA-filtered, through the xcore battery block). Pct is
 *                  derived with ADC_BATT_CELLS, an assumption until the cell
 *                  count question (SDD SS16 Q1) gets a config home; mV is
 *                  the measurement, pct is the display nicety.
 *   odoTotalMm   - needs DFlash persistence (doc 21 SS4.3) on top of the encoder.
 *   linkRttMs    - needs the HBT transaction the RTT measurement rides on.
 *   hwRev        - no board id source yet; the DPT flow of SDD SS10 reads it
 *                  before it reads anything else, so it is the first field to
 *                  fill once the hardware revision has a home.
 * linkErrRate is computed from the link's own counters below. */

/* Overflow-free average of the two side odometries (both absolute
 * accumulators): the distance the chassis covered, straight or curved. */
static uint32 link_sessionOdoMm(const XcoreEncoder *enc)
{
    return (enc->odoLeftMm / 2u) + (enc->odoRightMm / 2u)
         + ((enc->odoLeftMm & 1u) & (enc->odoRightMm & 1u));
}

/* CPU0's target is percent*10 of full scale; the telemetry field is mm/s.
 * The conversion is the calibration record's full-scale value (doc 34 SS8.2:
 * the same number CPU1 divides the measured speed by, so both columns stay
 * one consistent pair even after a REC_SET changed it). */
static sint16 link_targetToMmS(sint16 pct10)
{
    XcoreRecordLive live;
    sint32          mmS;

    XCORE_recordGet(&live);
    mmS = ((sint32)pct10 * (sint32)live.rec.fullScaleMmS) / 1000;

    if (mmS > 32767)
    {
        mmS = 32767;
    }
    if (mmS < -32768)
    {
        mmS = -32768;
    }
    return (sint16)mmS;
}

/* Event outbox drain (doc 34 SS3.4 / SS9.4): CPU0 pushes the DPT frames,
 * this core owns the TX path. peek + pop-around-send means a full TX queue
 * retries the SAME frame on the next tick instead of dropping it, so one
 * calibration produces exactly one frame. */
static void link_sendPendingEvents(void)
{
    XcoreEvtFrame frame;
    uint8         sent = 0u;

    while ((sent < XCORE_EVT_QUEUE_LEN) && (XCORE_evtPeek(&frame) != FALSE))
    {
        if (LINK_send(frame.type, frame.cid, frame.payload, frame.len) == FALSE)
        {
            break;                  /* backpressure: keep it pending          */
        }
        XCORE_evtPop();
        sent++;
    }
}

static void link_sendTelemetry(void)
{
    Link_Health    health;
    ProtocolStatus status;
    SF_Telemetry   tel;
    XcoreEncoder   enc;
    uint32         total;
    uint32         err;
    uint32         rate;
    uint32         perTenth;

    XCORE_statusGet(&status);
    XCORE_encoderRead(&enc);

    memset(&tel, 0, sizeof(tel));
    tel.uptimeMs  = STIME_nowMs();
    tel.state     = status.state;
    tel.faultCode = status.faultCode;   /* demo code set is 8 bit, widened as-is */
    tel.fwVer     = LINK_FW_VERSION;
    tel.vMeasLeft  = enc.vMeasLeftMmS;
    tel.vMeasRight = enc.vMeasRightMmS;
    tel.odoSessionMm = link_sessionOdoMm(&enc);

    /* Battery: CPU1 measures VIN (D24A J6-1 divider, AN4) at 100 Hz and
     * publishes the filtered mV; pct is the per-cell estimate. */
    tel.batteryMv  = XCORE_battGetMv();
    tel.batteryPct = ADC_battPctFromMv(tel.batteryMv);

    /* The command the drive is currently asked to follow (the CPU0 -> CPU1
     * target, before the servo loop acts on it). CPU0 is the block's only
     * writer, so reading it here is a plain shared-memory peek. */
    {
        sint16  tgtL, tgtR;
        boolean tgtEstop;

        (void)XCORE_motorGetTarget(&tgtL, &tgtR, &tgtEstop);
        tel.vTargetLeft  = link_targetToMmS(tgtL);
        tel.vTargetRight = link_targetToMmS(tgtR);
    }

    /* SDD SS6.1c / 22 SS5.5: linkErrRate keeps its meaning but changes source -
     * frames this core's codec rejected, over frames it saw, in units of 0.1%
     * (c6_proto/proto_frames.h declares that unit, so a plain percentage would
     * understate the link by a factor of ten). A frame that failed the CRC is in
     * the denominator only. The scaling divides first because err * 1000 overflows
     * uint32 on a noisy long-running link; 255 saturates at 25.5%, which already
     * means "the link is down" and is reported as ERR_LINK_LOST separately. */
    LINK_getHealth(&health);
    err   = health.stats.crcErrors + health.stats.seqErrors;
    total = health.stats.rxFrames + err;
    rate  = 0u;
    if ((err > 0u) && (total > 0u))
    {
        if (total < 1000u)
        {
            rate = (err * 1000u) / total;   /* provably within range */
        }
        else
        {
            perTenth = total / 1000u;   /* frames per 0.1%, >= 1 here */
            rate = err / perTenth;
        }
        if (rate > 255u)
        {
            rate = 255u;
        }
    }
    tel.linkErrRate = (uint8)rate;

    /* seq is stamped by the link, which owns the order frames actually go out in. */
    (void)LINK_sendTelemetry(&tel);
}

/* Bench speed line: the figures this core puts into telemetry vMeasL/R and
 * odoSession, on the CPU0 console at 1 Hz so a bench check of the speed
 * display needs no phone on the link. Signed values, hence XCORE_logi. */
#define LINK_SPEED_PERIOD_MS     1000u

static void link_speedPrint(void)
{
    XcoreEncoder enc;
    sint32       vals[4];

    XCORE_encoderRead(&enc);
    vals[0] = enc.vMeasLeftMmS;
    vals[1] = enc.vMeasRightMmS;
    vals[2] = (sint32)link_sessionOdoMm(&enc);
    vals[3] = enc.alive ? 1 : 0;

    XCORE_logi("SPD=", vals, 4u);
}
